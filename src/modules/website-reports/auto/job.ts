import 'server-only';
import { createAdminClient } from '@/lib/supabase/admin';
import type { Json } from '@/lib/types/database';
import { logEvent } from '@/lib/audit/log';
import { env } from '@/lib/env';
import { fetchHomepage } from '../fetch';
import { enqueueEmail } from '@/lib/outbox/enqueue';
import { decideAutoGeneration, AUTO_DEDUP_WINDOW_DAYS } from './policy';
import { generateQuickscanContent, QS_PROMPT_VERSION, type QuickscanGenDeps } from './quickscan-content';
import { buildQuickscanSite, quickscanScoreColumns, quickscanMarkdown } from './quickscan-schema';
import { renderQuickscanPdf } from './pdf-service';
import type { ReportInputContext } from '../types';

/**
 * WAF-4 auto-pilot worker job (quickscan path). Runs under the service role from the outbox worker (no
 * authenticated actor) for an `outbox` row with `channel = 'report_generation'`.
 *
 * Order is cost-first: re-evaluate the policy (global daily cap + per-domain dedup) IMMEDIATELY before any
 * spend, then SSRF-safe fetch -> AI writes the Swiss-German quickscan `site` dict (per-report cost cap
 * enforced here) -> store it on the report row. When AUTO_SEND_ENABLED, the report is system-approved and the
 * PDF is rendered by the EXTERNAL quickscan service (exact weasyprint) and emailed to the address that
 * requested the analysis. It NEVER auto-creates a CRM row. System reports are marked by `created_by = null`,
 * which is also how the daily cap is counted. Returns a status; only throws on unexpected infra errors so the
 * worker can retry (no AI spent yet at that point).
 */
type AutoReportJobResult =
  | { status: 'skipped'; reason: string }
  | { status: 'generated'; reportId: string; sent: boolean }
  | { status: 'failed'; reason: string };

export type AutoReportJobDeps = QuickscanGenDeps & { fetchHomepageImpl?: typeof fetchHomepage };

type Admin = ReturnType<typeof createAdminClient>;
const BUCKET = 'website-reports';

function localeOf(v: string | null): 'de' | 'fr' | 'en' {
  return v === 'fr' || v === 'en' ? v : 'de';
}
function hostOf(url: string | null): string | null {
  if (!url) return null;
  try {
    return new URL(url).host || null;
  } catch {
    return null;
  }
}
async function failReport(admin: Admin, reportId: string, reason: string): Promise<void> {
  await admin.from('website_analysis_reports').update({ generation_status: 'failed', error_summary: reason }).eq('id', reportId);
  await logEvent({
    action: 'website_report.generation_failed', actorId: null, actorType: 'system', severity: 'warning',
    entityType: 'website_report', entityId: reportId, metadata: { reason, auto: true }, source: 'system_job',
  });
}

export async function runAutoReportJob(funnelSubmissionId: string, deps: AutoReportJobDeps = {}): Promise<AutoReportJobResult> {
  const admin = createAdminClient();

  // 1) Load the submission.
  const { data: funnel } = await admin
    .from('funnel_submissions')
    .select('id, source_type, website_url, normalized_domain, first_name, last_name, email, payload, locale, company_id, contact_id')
    .eq('id', funnelSubmissionId)
    .maybeSingle();
  if (!funnel) return { status: 'skipped', reason: 'submission_not_found' };

  // 2) Cost wall: today's auto-generations (system = created_by NULL) + per-domain recency dedup.
  const startOfDay = new Date();
  startOfDay.setUTCHours(0, 0, 0, 0);
  const { count: todayAutoCount } = await admin
    .from('website_analysis_reports')
    .select('id', { count: 'exact', head: true })
    .is('created_by', null)
    .gte('created_at', startOfDay.toISOString());

  let domainHasRecentReport = false;
  if (funnel.normalized_domain) {
    const since = new Date(Date.now() - AUTO_DEDUP_WINDOW_DAYS * 86_400_000).toISOString();
    const { count: dom } = await admin
      .from('website_analysis_reports')
      .select('id', { count: 'exact', head: true })
      .eq('normalized_domain', funnel.normalized_domain)
      .eq('is_current', true)
      .eq('generation_status', 'succeeded')
      .gte('created_at', since);
    domainHasRecentReport = (dom ?? 0) > 0;
  }

  const decision = decideAutoGeneration({
    enabled: env.autoGenerateEnabled,
    sourceType: funnel.source_type,
    hasWebsiteUrl: !!funnel.website_url,
    domainHasRecentReport,
    todayAutoCount: todayAutoCount ?? 0,
    dailyCap: env.autoGenerateDailyCap,
  });
  if (!decision.allowed) {
    await logEvent({
      action: 'website_report.auto_skipped', actorId: null, actorType: 'system',
      entityType: 'funnel', entityId: funnel.id,
      metadata: { reason: decision.reason, domain: funnel.normalized_domain }, source: 'system_job',
    });
    return { status: 'skipped', reason: decision.reason };
  }

  const websiteUrl = funnel.website_url;
  if (!websiteUrl) return { status: 'skipped', reason: 'no_website' };

  // 3) Build the input context + create the report row as a SYSTEM report (created_by NULL).
  const [companyName, contactName] = await Promise.all([
    funnel.company_id
      ? admin.from('companies').select('company_name').eq('id', funnel.company_id).maybeSingle().then((r) => r.data?.company_name ?? null)
      : Promise.resolve(null),
    funnel.contact_id
      ? admin.from('company_contacts').select('name, email').eq('id', funnel.contact_id).maybeSingle().then((r) => (r.data ? r.data.name || r.data.email : null))
      : Promise.resolve(null),
  ]);

  const context: ReportInputContext = {
    website_url: websiteUrl,
    normalized_domain: funnel.normalized_domain,
    locale: localeOf(funnel.locale),
    funnel: { first_name: funnel.first_name, last_name: funnel.last_name, email: funnel.email, payload: (funnel.payload as Record<string, unknown>) ?? {} },
    company: funnel.company_id ? { name: companyName } : null,
    contact: funnel.contact_id ? { name: contactName } : null,
  };

  const { data: existing } = await admin
    .from('website_analysis_reports')
    .select('version')
    .eq('funnel_submission_id', funnel.id)
    .order('version', { ascending: false })
    .limit(1);
  const nextVersion = (existing && existing[0]?.version ? existing[0].version : 0) + 1;
  await admin.from('website_analysis_reports').update({ is_current: false }).eq('funnel_submission_id', funnel.id).eq('is_current', true);

  const { data: row, error } = await admin
    .from('website_analysis_reports')
    .insert({
      funnel_submission_id: funnel.id,
      version: nextVersion,
      is_current: true,
      company_id: funnel.company_id,
      contact_id: funnel.contact_id,
      website_url: websiteUrl,
      normalized_domain: funnel.normalized_domain,
      generation_status: 'queued',
      review_status: 'review_needed',
      input_snapshot: context as unknown as Json,
      created_by: null,
      updated_by: null,
    })
    .select('*')
    .single();
  if (error || !row) return { status: 'failed', reason: 'insert_failed' };

  await logEvent({
    action: 'website_report.generation_requested', actorId: null, actorType: 'system',
    entityType: 'website_report', entityId: row.id,
    metadata: { domain: funnel.normalized_domain, version: nextVersion, auto: true, engine: 'quickscan' }, source: 'system_job',
  });

  // 4) SSRF-safe homepage fetch.
  await admin.from('website_analysis_reports').update({ generation_status: 'fetching' }).eq('id', row.id);
  const fetchImpl = deps.fetchHomepageImpl ?? fetchHomepage;
  let fetchRes;
  try {
    fetchRes = await fetchImpl(websiteUrl, {});
  } catch {
    await failReport(admin, row.id, 'unreachable');
    return { status: 'failed', reason: 'unreachable' };
  }
  if (!fetchRes.ok) {
    await failReport(admin, row.id, fetchRes.reason);
    return { status: 'failed', reason: fetchRes.reason };
  }
  await admin.from('website_analysis_reports').update({ crawl_snapshot: fetchRes.snapshot as unknown as Json }).eq('id', row.id);

  // 5) AI writes the quickscan content (per-report cost cap enforced here).
  await admin.from('website_analysis_reports').update({ generation_status: 'analyzing' }).eq('id', row.id);
  const gen = await generateQuickscanContent(fetchRes.snapshot, context, { getProvider: deps.getProvider });
  if (!gen.ok) {
    const reason = gen.detail ? `${gen.reason}:${gen.detail}` : gen.reason;
    await failReport(admin, row.id, reason);
    return { status: 'failed', reason };
  }
  if (gen.cost > env.websiteReportMaxCost) {
    await failReport(admin, row.id, 'cost_exceeded');
    return { status: 'failed', reason: 'cost_exceeded' };
  }

  const site = buildQuickscanSite(gen.content, { domain: funnel.normalized_domain });
  const cols = quickscanScoreColumns(gen.content.scores);
  await admin
    .from('website_analysis_reports')
    .update({
      generation_status: 'succeeded',
      review_status: 'review_needed',
      report_json: site as unknown as Json,
      report_markdown: quickscanMarkdown(gen.content),
      model_provider: gen.provider,
      model_name: gen.model,
      prompt_version: QS_PROMPT_VERSION,
      cost_estimate: gen.cost,
      token_usage: gen.usage as unknown as Json,
      generated_at: new Date().toISOString(),
      ...cols,
    })
    .eq('id', row.id);

  // 6) System auto-approve (the review_status the deliver gate requires).
  await admin
    .from('website_analysis_reports')
    .update({ review_status: 'approved', reviewed_at: new Date().toISOString(), reviewed_by: null })
    .eq('id', row.id);
  await logEvent({
    action: 'website_report.reviewed', actorId: null, actorType: 'system',
    entityType: 'website_report', entityId: row.id, oldStatus: 'review_needed', newStatus: 'approved',
    metadata: { decision: 'approved', auto: true }, source: 'system_job',
  });

  // 7) Auto-send (optional) — render via the external quickscan service, then email to the submitter.
  if (!env.autoSendEnabled || !env.websiteReportDeliveryEnabled) return { status: 'generated', reportId: row.id, sent: false };
  const email = (funnel.email ?? '').trim();
  if (!email) return { status: 'generated', reportId: row.id, sent: false };

  const rendered = await renderQuickscanPdf(site);
  if (!rendered.ok) {
    await logEvent({
      action: 'report_delivery.failed', actorId: null, actorType: 'system', severity: 'warning',
      entityType: 'website_report', entityId: row.id, metadata: { report_id: row.id, reason: rendered.reason, auto: true }, source: 'system_job',
    });
    return { status: 'generated', reportId: row.id, sent: false };
  }

  const { data: delivery, error: dErr } = await admin
    .from('website_report_deliveries')
    .insert({
      report_id: row.id,
      funnel_submission_id: funnel.id,
      contact_id: funnel.contact_id,
      company_id: funnel.company_id,
      to_email: email,
      status: 'rendering',
      created_by: null,
      updated_by: null,
    })
    .select('*')
    .single();
  if (dErr || !delivery) return { status: 'generated', reportId: row.id, sent: false };

  const path = `${row.id}/${delivery.id}.pdf`;
  const up = await admin.storage.from(BUCKET).upload(path, rendered.pdf, { contentType: 'application/pdf', upsert: true });
  if (up.error) {
    await admin.from('website_report_deliveries').update({ status: 'failed', failed_at: new Date().toISOString(), error_summary: 'pdf_upload_failed' }).eq('id', delivery.id);
    return { status: 'generated', reportId: row.id, sent: false };
  }
  await admin
    .from('website_report_deliveries')
    .update({ pdf_bucket: BUCKET, pdf_path: path, pdf_size_bytes: rendered.pdf.length })
    .eq('id', delivery.id);

  const domain = funnel.normalized_domain || hostOf(websiteUrl) || 'Ihre Website';
  const subject = `Ihre Website Analyse für ${domain}`;
  const firstName = (funnel.first_name ?? '').trim();
  let outboxId: string | null = null;
  try {
    outboxId = await enqueueEmail(
      {
        to: email,
        template: 'website_report',
        subject,
        replyTo: env.notificationTo,
        vars: {
          firstName,
          hello: 'Hallo',
          intro: 'Im Anhang finden Sie Ihre Website Analyse als PDF. Bei Fragen antworten Sie einfach auf diese Email.',
          signoff: 'Freundliche Grüsse, das amai Team',
        },
        attachment: { bucket: BUCKET, path, filename: site.file, mimeType: 'application/pdf' },
      },
      `website_report:${row.id}:${delivery.id}`,
    );
  } catch {
    outboxId = null;
  }
  if (!outboxId) {
    await admin.from('website_report_deliveries').update({ status: 'failed', failed_at: new Date().toISOString(), error_summary: 'enqueue_failed' }).eq('id', delivery.id);
    return { status: 'generated', reportId: row.id, sent: false };
  }

  await admin.from('website_report_deliveries').update({ status: 'sending', outbox_id: outboxId, subject }).eq('id', delivery.id);
  await logEvent({
    action: 'report_delivery.email_enqueued', actorId: null, actorType: 'system',
    entityType: 'report_delivery', entityId: delivery.id,
    metadata: { report_id: row.id, outbox_id: outboxId, auto: true }, source: 'system_job',
  });

  return { status: 'generated', reportId: row.id, sent: true };
}
